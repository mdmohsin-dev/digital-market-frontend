/**
 * Derives featured products from the main product list, sorted by
 * rating so the strongest performers surface first.
 *
 * Later this becomes: `await fetch("/api/products?featured=true")`
 * — same return shape, so callers don't need to change.
 */
export function getFeaturedProducts(): Product[] {
  return products
    .filter((product) => product.featured)
    .sort((a, b) => b.rating - a.rating);
}